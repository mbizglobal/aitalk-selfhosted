import { NextResponse } from 'next/server'

//   <script src="https://www.aitalk.ch/booking.min.js" data-agent-id="AGENT_ID" data-lang="de" async></script>
export async function GET() {
  const script = `
(function () {
  var current = document.currentScript;
  if (!current) {
    var list = document.querySelectorAll('script[src*="/booking.min.js"]');
    current = list[list.length - 1];
  }
  if (!current) return;
  var agentId = current.getAttribute('data-agent-id');
  if (!agentId || !/^[A-Za-z0-9_-]{1,64}$/.test(agentId)) return;
  var base;
  try { base = current.getAttribute('data-base-url') || new URL(current.src).origin; } catch (e) { return; }
  var baseOrigin;
  try { baseOrigin = new URL(base).origin; } catch (e) { return; }
  var lang = current.getAttribute('data-lang') || document.documentElement.getAttribute('lang') || '';
  var src = baseOrigin + '/book/' + encodeURIComponent(agentId) + (lang ? '?lang=' + encodeURIComponent(lang) : '');

  var iframe = document.createElement('iframe');
  iframe.src = src;
  iframe.title = 'Online booking';
  iframe.setAttribute('loading', 'lazy');
  iframe.style.cssText = 'display:block;width:100%;max-width:480px;height:640px;border:0;margin:0 auto;background:transparent;';

  var targetSel = current.getAttribute('data-target');
  var target = targetSel ? document.querySelector(targetSel) : null;
  if (target) target.appendChild(iframe);
  else current.parentNode.insertBefore(iframe, current.nextSibling);

  window.addEventListener('message', function (ev) {
    if (ev.origin !== baseOrigin || ev.source !== iframe.contentWindow) return;
    var d = ev.data;
    if (!d || d.type !== 'AITALK_BOOKING_HEIGHT' || d.agentId !== agentId) return;
    var h = Number(d.h);
    if (h > 120 && h < 4000) iframe.style.height = h + 'px';
  });
})();
`
  return new NextResponse(script, {
    headers: {
      'Content-Type': 'application/javascript; charset=utf-8',
      'Cache-Control': 'public, max-age=3600',
    },
  })
}
